"""Design tokens: shadcn/ui variable names, HSL triplets (no hsl() wrapper). Tabloid + Target brand.

Core values come from shared-design-tokens.json (shared with the newsletter).

Single source for both the CSS custom properties prepended to style.css and
assets/design-tokens.json (for the future newsletter)."""

import json
from pathlib import Path

# Shared with the newsletter: verbatim copy of the data repo's
# publications/newsletter_data/design_tokens.json. Its values win for every key it defines.
SHARED_PATH = Path(__file__).resolve().parent / "shared-design-tokens.json"
SHARED = json.loads(SHARED_PATH.read_text(encoding="utf-8"))

RADIUS = SHARED["radius"]
_sans = SHARED["font"]["sans"]
FONTS = {
    "font-sans": _sans,
    "font-display": SHARED["font"].get("display", _sans),
    "font-mono": 'ui-monospace, SFMono-Regular, Menlo, Consolas, "Liberation Mono", monospace',
}
BREAKPOINTS = {"sm": "640px", "md": "768px", "lg": "1024px"}

# Site-only extension tokens (not in the shared set): popover, masthead, link, status colours.
SITE_LIGHT = {
    "popover": "0 0% 100%", "popover-foreground": "0 0% 5%",
    "primary-deep": "0 0% 3%",
    "accent-text": "3 76% 38%",
    "destructive-text": "0 72% 40%",
    "success": "142 71% 35%", "success-text": "142 72% 25%",
    "warning": "38 92% 50%", "warning-text": "26 90% 30%",
    "silver": "215 16% 86%", "silver-foreground": "222 47% 15%",
    "link": "3 76% 36%",
    "masthead": "50 100% 65%", "masthead-foreground": "0 0% 5%",
    "hero": "0 0% 5%", "hero-foreground": "0 0% 100%",
    "shadow": "0 0% 5%",
}
SITE_DARK = {
    "popover": "0 0% 10%", "popover-foreground": "0 0% 96%",
    "primary-deep": "0 0% 2%",
    "accent-text": "50 100% 70%",
    "destructive-text": "0 90% 74%",
    "success": "142 69% 50%", "success-text": "142 69% 68%",
    "warning": "38 92% 55%", "warning-text": "43 96% 70%",
    "silver": "215 16% 72%", "silver-foreground": "222 47% 11%",
    "link": "50 100% 70%",
    "masthead": "50 100% 60%", "masthead-foreground": "0 0% 5%",
    "hero": "0 0% 3%", "hero-foreground": "0 0% 100%",
    "shadow": "0 0% 0%",
}
LIGHT = {**SITE_LIGHT, **SHARED["light"]}
DARK = {**SITE_DARK, **SHARED["dark"]}


def _block(selector: str, values: dict, extra: dict | None = None) -> str:
    lines = [f"  --{k}: {v};" for k, v in values.items()]
    lines += [f"  --{k}: {v};" for k, v in (extra or {}).items()]
    return selector + " {\n" + "\n".join(lines) + "\n}\n"


def css() -> str:
    base = _block(":root", LIGHT, {"radius": RADIUS, **FONTS})
    dark_manual = _block(':root[data-theme="dark"]', DARK)
    dark_auto = "@media (prefers-color-scheme: dark) {\n" + _block(':root:not([data-theme="light"])', DARK) + "}\n"
    return "/* generated by site/build.py from site/tokens.py */\n" + base + dark_auto + dark_manual


def as_json() -> dict:
    """The shared newsletter tokens, unchanged, plus the site-only extensions."""
    out = dict(SHARED)
    out["site_extensions"] = {
        "light": SITE_LIGHT, "dark": SITE_DARK, "fonts": FONTS, "breakpoints": BREAKPOINTS,
        "radius_scale": {"lg": RADIUS, "md": f"calc({RADIUS} - 2px)", "sm": f"calc({RADIUS} - 4px)"},
        "semantic": {"championship": "accent", "runner_up": "silver", "bye": "primary",
                     "verified": "success", "rescored": "warning", "loss": "destructive"},
    }
    return out
